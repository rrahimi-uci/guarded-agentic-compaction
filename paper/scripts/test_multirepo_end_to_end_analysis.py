def test_decision_flips_with_n(tmp_path):
    """A repository with n = 200 and k = 3 admits; k = 4 does not (Appendix A.3)."""
    for k, decision in ((3, "admit"), (4, "retire")):
        d = tmp_path / f"r{k}" / "o__r"
        d.mkdir(parents=True)
        groups = [group("o/r", i, arm(i >= k)) for i in range(200)]
        (d / "calibration_groups.json").write_text(json.dumps(groups))
        (d / "selection.json").write_text(json.dumps({"disjoint": True}))
        (d / "ledger.json").write_text(json.dumps({"spent_usd": 1.0}))
        s = ana.build_summary(tmp_path / f"r{k}")
        cert = s["repositories"][0]["certificate"]
        assert (cert["n"], cert["k"], cert["decision"]) == (200, k, decision)
        assert s["admitted_repositories"] == (["o/r"] if decision == "admit" else [])
        assert s["repositories"][0]["shortfall_vs_target_n"] == 0


