BASE = {"requests": 4, "tokens": 600, "latency_ms": 3000, "cost_usd": 0.0008}
COMPILED = {"requests": 1, "tokens": 150, "latency_ms": 800, "cost_usd": 0.0002}
FALLBACK = {"requests": 5, "tokens": 700, "latency_ms": 3400, "cost_usd": 0.0009}
MANUAL = {"requests": 1, "tokens": 120, "latency_ms": 700, "cost_usd": 0.0001}


def arm(met, *, eligible=True, dispatched=True, abstained=False, fallback=False, res=None):
    return {"eligible": eligible, "dispatched": dispatched, "verifier_abstained": abstained,
            "contract_met": met, "fallback": fallback, **(res or COMPILED)}


def group(repo, i, compiled, baseline_met=True, manual_met=True):
    return {"repo": repo, "number": 1000 + i, "author": f"user-{repo.split('/')[1]}-{i:03d}",
            "created_day": f"2026-03-{1 + i % 28:02d}", "class": ("open", "merged", "closed_unmerged")[i % 3],
            "arms": {"compiled": compiled, "baseline": arm(baseline_met, res=BASE),
                     "manual": arm(manual_met, res=MANUAL)}}


def alpha_groups():
    """40 groups, 36 dispatched, 4 abstained with fallback (3 met); 0 violations; baseline misses 2."""
    repo, out = "synthetic-org/alpha-fixture", []
    for i in range(40):
        if i < 4:
            comp = arm(i != 0, dispatched=False, abstained=True, fallback=True, res=FALLBACK)
        else:
            comp = arm(True)
        out.append(group(repo, i, comp, baseline_met=i not in (10, 11)))
    return out


def beta_groups():
    """44 recorded: 1 ineligible, 3 eligible-but-excluded, 40 in n (2 violations, 3 abstentions)."""
    repo, out = "synthetic-org/beta-fixture", []
    for i in range(44):
        if i == 0:
            comp, bm = arm(False, eligible=False, dispatched=False), True
        elif i in (1, 2, 3):
            comp, bm = arm(False, dispatched=False), True
        elif i in (4, 5):
            comp, bm = arm(False), True  # violations; baseline met -> compiled-only misses
        elif i in (6, 7, 8):
            comp, bm = arm(True, dispatched=False, abstained=True, fallback=True, res=FALLBACK), True
        else:
            comp, bm = arm(True), (i % 9 != 0)
        out.append(group(repo, i, comp, baseline_met=bm))
    return out


def build_fixture(directory: Path) -> None:
    spec = {
        "synthetic-org__alpha-fixture": (alpha_groups(), {"disjoint": True, "calibration": list(range(40))}, None, 0.21),
        "synthetic-org__beta-fixture": (beta_groups(), {"disjoint": True, "calibration": list(range(44))}, None, 0.19),
        "synthetic-org__gamma-fixture": (None, {"disjoint": True, "status": "retired", "calibration": []},
                                         {"status": "retired", "reason": "compiler admits no artifact"}, 0.09),
    }
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "FIXTURE_LABEL.txt").write_text(LABEL + "\nGenerated by paper/scripts/test_multirepo_end_to_end_analysis.py.\n")
    for name, (groups, selection, compile_, spent) in spec.items():
        d = directory / name
        d.mkdir(parents=True, exist_ok=True)
        dump = lambda p, o: (d / p).write_text(json.dumps(o, indent=2, sort_keys=True) + "\n")  # noqa: E731
        dump("selection.json", {**selection, "label": LABEL})
        if groups is not None:
            dump("calibration_groups.json", groups)
        if compile_ is not None:
            dump("compile.json", {**compile_, "label": LABEL})
        dump("ledger.json", {"spent_usd": spent, "label": LABEL})


