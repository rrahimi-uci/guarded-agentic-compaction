def test_bound_matches_closed_form_and_beta():
    conf_a, conf_b = 1 - 0.1 / 11, 0.90
    assert ana.rule_confidence("grid_m1") == pytest.approx(conf_a)
    assert ana.rule_confidence("grid_m1", m=2) == pytest.approx(1 - 0.1 / 22)
    assert ana.upper_bound(0, 200, "grid_m1") == pytest.approx(1 - (1 - conf_a) ** (1 / 200))
    assert ana.upper_bound(0, 200, "grid_m1") == pytest.approx(0.0232, abs=5e-5)
    assert ana.upper_bound(3, 132, "single_rule") == pytest.approx(beta.ppf(conf_b, 4, 129))
    assert ana.upper_bound(3, 132, "single_rule") == pytest.approx(0.0499, abs=5e-5)
    assert ana.upper_bound(7, 7, "grid_m1") == 1.0
    assert ana.upper_bound(0, 92, "grid_m1") == pytest.approx(0.0498, abs=5e-5)
    assert ana.upper_bound(0, 92, "grid_m1", m=2) == pytest.approx(0.0569, abs=5e-5)


@pytest.mark.parametrize("rule,table", sorted(ana.APPENDIX_A3_FLOORS.items()))
def test_decision_floors_match_appendix_a3(rule, table):
    for n, k in table.items():
        assert ana.max_admissible_k(n, rule) == k, (rule, n)
        assert ana.upper_bound(k, n, rule) <= 0.05 < ana.upper_bound(k + 1, n, rule)
    assert ana.check_appendix_a3() == []


def test_floor_edge_cases():
    assert ana.max_admissible_k(40) == -1  # cannot admit even with zero violations
    assert ana.max_admissible_k(92, "grid_m1", m=2) == -1  # A.3: m = 2, n = 92 none
    assert ana.max_admissible_k(106, "grid_m1", m=2) == 0
    assert ana.max_admissible_k(200, "grid_m1", m=2) == 2
    assert ana.max_admissible_k(300, "grid_m1", m=2) == 5


def test_zero_violation_compiled_only_bound_matches_a3():
    for n, expected in ((200, 0.0149), (400, 0.0075), (800, 0.0037)):
        assert 1 - 0.05 ** (1 / n) == pytest.approx(expected, abs=5e-5)
        groups = [group("a/b", i, arm(True)) for i in range(n)]
        assert ana.paired(groups)["compiled_only_misses_upper95"] == pytest.approx(expected, abs=5e-5)


def test_mcnemar_exact():
    assert ana.mcnemar_exact(0, 0) == 1.0
    assert ana.mcnemar_exact(3, 3) == 1.0
    assert ana.mcnemar_exact(0, 5) == pytest.approx(binomtest(0, 5, 0.5).pvalue) == pytest.approx(2 / 32)
    assert ana.mcnemar_exact(2, 8) == pytest.approx(binomtest(2, 10, 0.5).pvalue)


