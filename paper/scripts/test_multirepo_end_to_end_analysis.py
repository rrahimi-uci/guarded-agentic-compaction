def test_paired_and_fallback():
    s = ana.summarise_groups(alpha_groups())
    p = s["paired"]
    assert (p["both_met"], p["baseline_only_met"], p["compiled_only_met"], p["neither_met"]) == (37, 1, 2, 0)
    assert p["mcnemar_exact_p_two_sided"] == pytest.approx(binomtest(1, 3, 0.5).pvalue)
    assert p["compiled_only_misses"] == 1  # the fallback group whose contract was missed while baseline met it
    assert p["compiled_only_misses_upper95"] == pytest.approx(beta.ppf(0.95, 2, 39))
    assert s["fallback"] == {"abstained": 4, "fallback_groups": 4, "fallback_contract_met": 3, "fallback_contract_missed": 1}
