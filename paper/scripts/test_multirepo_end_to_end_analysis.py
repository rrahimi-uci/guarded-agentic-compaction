def test_validate_group_rejects_bad_rows():
    g = alpha_groups()[5]
    bad = json.loads(json.dumps(g))
    del bad["arms"]["manual"]
    with pytest.raises(ValueError, match="missing arm"):
        ana.validate_group(bad)
    bad = json.loads(json.dumps(g))
    bad["arms"]["compiled"]["verifier_abstained"] = True
    with pytest.raises(ValueError, match="both dispatched and abstained"):
        ana.validate_group(bad)
    bad = json.loads(json.dumps(g))
    del bad["arms"]["baseline"]["tokens"]
    with pytest.raises(ValueError, match="missing keys"):
        ana.validate_group(bad)


