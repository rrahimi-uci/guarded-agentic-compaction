def test_run_is_idempotent_and_matches_committed_fixture(fx, tmp_path):
    out = tmp_path / "out"
    ana.run(fx, out / "summary.json", out / "t.tex", LABEL)
    first = ((out / "summary.json").read_bytes(), (out / "t.tex").read_bytes())
    ana.run(fx, out / "summary.json", out / "t.tex", LABEL)
    assert first == ((out / "summary.json").read_bytes(), (out / "t.tex").read_bytes())
    assert b"generated_at" not in first[0]
    # the committed synthetic fixture is the deterministic output of build_fixture
    assert (FIXTURE / "summary.json").read_bytes() == first[0]
    assert (FIXTURE / "multirepo_end_to_end.tex").read_bytes() == first[1]
    for path in sorted(fx.rglob("*.json")) + [fx / "FIXTURE_LABEL.txt"]:
        assert (FIXTURE / path.relative_to(fx)).read_bytes() == path.read_bytes(), path


def test_git_diff_empty_on_regeneration(tmp_path):
    """Regenerating twice into a scratch git repository leaves `git diff` empty."""
    results = tmp_path / "repo" / "results"
    build_fixture(results)
    cmd = [sys.executable, str(Path(ana.__file__)), "--results-dir", str(results),
           "--table-out", str(tmp_path / "repo" / "table.tex"), "--label", LABEL]
    git = lambda *a: subprocess.run(["git", *a], cwd=tmp_path / "repo", capture_output=True, text=True, check=True)  # noqa: E731
    git("init", "-q")
    subprocess.run(cmd, check=True, capture_output=True)
    git("add", "-A")
    git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "first")
    subprocess.run(cmd, check=True, capture_output=True)
    assert git("diff").stdout == ""
    assert git("status", "--porcelain").stdout == ""


