def _cluster_stats(frame: pd.DataFrame, ids: Sequence[int]) -> dict[str, Any]:
    sub = frame.loc[[i for i in ids if i in frame.index]]
    stats = {"n": len(ids), "matched": len(sub), "distinct_days": int(sub["day"].nunique()), "distinct_months": int(sub["month"].nunique()), "distinct_authors": int(sub["author"].nunique()),
             "day_span_days": int((pd.to_datetime(sub["day"]).max() - pd.to_datetime(sub["day"]).min()).days) if len(sub) else None}
    for key in ("distinct_days", "distinct_months", "distinct_authors"):
        stats[f"U_at_{key}"] = cp_upper(0, stats[key], 1 - gamma_for(1))
    return stats


