def _ids(block: dict[str, Any], role: str) -> set[int]:
    key = "record_number" if "record_number" in (block["selection"][role][0] if block["selection"][role] else {}) else "issue_number"
    return {int(x[key]) for x in block["selection"][role]}


def _cal_ids(block: dict[str, Any]) -> set[int] | None:
    comp = block.get("compiler") or (block.get("compilers") or {}).get("learned_gate")
    if not comp or "splits" not in comp:
        return None
    return {int(g.rsplit(":", 1)[1]) for g in comp["splits"]["groups"]["calibration"]}


