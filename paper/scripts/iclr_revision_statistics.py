def cmd_order() -> dict[str, Any]:
    out: dict[str, Any] = {"families": {}}
    for fam, spec in FAMILIES.items():
        data = load(spec["path"])
        base = {int(r[spec["id"]]): r for r in rows_for(fam, "baseline")}
        comp = {int(r[spec["id"]]): r for r in rows_for(fam, "compiled")}
        if "schedule" in data:
            orders = {int(s["record_number"]): tuple(s["order"]) for s in data["schedule"]}
            design = "per-record permutation cycle; arms sequential (concurrency 1)"
        else:
            orders = {int(k): tuple(v) for k, v in data["condition_order"]["primary"]["assignments"].items()}
            design = data["condition_order"]["primary"]["method"] + "; blocked, concurrency 8"
        by_perm: dict[str, dict[str, Any]] = {}
        for perm in sorted(set(orders.values())):
            ids = [k for k, v in orders.items() if v == perm and k in base and k in comp]
            b = sum(float(base[k]["metrics"]["wall_latency_ms"]) for k in ids)
            c = sum(float(comp[k]["metrics"]["wall_latency_ms"]) for k in ids)
            by_perm["->".join(perm)] = {"n": len(ids), "wall_latency_reduction": 1 - c / b if b else None}
        pos_comp = Counter(v.index(spec["arms"]["compiled"]) for v in orders.values())
        by_position: dict[str, Any] = {}
        for pos in range(3):
            ids = [k for k, v in orders.items() if v.index(spec["arms"]["compiled"]) == pos and k in base and k in comp]
            b = sum(float(base[k]["metrics"]["wall_latency_ms"]) for k in ids)
            c = sum(float(comp[k]["metrics"]["wall_latency_ms"]) for k in ids)
            by_position[str(pos)] = {"n": len(ids), "wall_latency_reduction": 1 - c / b if b else None}
        ids = sorted(set(base) & set(comp))
        wall = 1 - sum(float(comp[k]["metrics"]["wall_latency_ms"]) for k in ids) / sum(float(base[k]["metrics"]["wall_latency_ms"]) for k in ids)
