# --------------------------------------------------------------------------- helpers
def load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text())


def dump(name: str, payload: dict[str, Any]) -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{name}.json"
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    return path


def write_table(name: str, subcommand: str, body: str) -> Path:
    TABLES.mkdir(parents=True, exist_ok=True)
    path = TABLES / f"{name}.tex"
    path.write_text(GENERATED.format(name=subcommand) + body.rstrip() + "\n")
    return path


def rows_for(family: str, arm: str) -> list[dict[str, Any]]:
    spec = FAMILIES[family]
    data = load(spec["path"])
    cond = spec["arms"][arm]
    rows = [r for r in data["results"] if r["condition"] == cond and int(r.get("repeat", 0)) == 0]
    return sorted(rows, key=lambda r: int(r[spec["id"]]))


def exact(family: str, row: dict[str, Any]) -> bool:
    return bool(row["quality"][FAMILIES[family]["exact"]])


def mean_median(values: Sequence[float]) -> tuple[float, float]:
    return float(statistics.mean(values)), float(statistics.median(values))


def bootstrap_ci(values: Sequence[float], stat: Callable = np.mean, *, seed: int = BOOTSTRAP_SEED) -> tuple[float, float]:
    """Same estimator as ``github_live_study.bootstrap_ci`` (percentile, 10,000 resamples)."""
    if not values:
        return float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    array = np.asarray(values, dtype=float)
    idx = rng.integers(0, len(array), size=(BOOTSTRAP_N, len(array)))
    samples = stat(array[idx], axis=1)
    lo, hi = np.quantile(samples, [0.025, 0.975])
    return float(lo), float(hi)


def bootstrap_ci_mean_legacy(values: Sequence[float]) -> tuple[float, float]:
    """Byte-identical reimplementation of ``github_live_study.bootstrap_ci`` (rng.choice)."""
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    array = np.asarray(values, dtype=float)
    samples = rng.choice(array, size=(BOOTSTRAP_N, len(array)), replace=True).mean(axis=1)
    lo, hi = np.quantile(samples, [0.025, 0.975])
    return float(lo), float(hi)


def wilcoxon_p(diffs: Sequence[float]) -> float:
    try:
        return float(wilcoxon(list(diffs), zero_method="zsplit", alternative="two-sided").pvalue)
    except ValueError:
        return 1.0


def cp_upper(k: int, n: int, conf: float) -> float:
    if n == 0 or k >= n:
        return 1.0
    if k == 0:
        return 1.0 - (1.0 - conf) ** (1.0 / n)
    return float(beta.ppf(conf, k + 1, n - k))


def one_sided_upper_95(k: int, n: int) -> float:
    return cp_upper(k, n, 0.95)


def gamma_for(m: int) -> float:
    return DELTA / (m * GRID_SIZE)


def n_min(m: int) -> int:
    n = 1
    while cp_upper(0, n, 1.0 - gamma_for(m)) > ALPHA:
        n += 1
    return n


def parse_grid_rows(notes: str) -> list[dict[str, Any]]:
    marker = "grid rows: "
    if marker not in notes:
        return []
    return ast.literal_eval(notes.split(marker, 1)[1].strip())


def fmt(x: float, nd: int = 1) -> str:
    return f"{x:,.{nd}f}"


def sci(x: float) -> str:
    return f"{x * 1e4:.2f}"  # USD x 1e-4


