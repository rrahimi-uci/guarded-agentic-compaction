def cmd_multiplicity() -> dict[str, Any]:
    out: dict[str, Any] = {"alpha": ALPHA, "delta": DELTA, "grid_size": GRID_SIZE,
                           "n_min": {str(m): n_min(m) for m in (1, 2, 3, 4, 8, 16)},
                           "u_at_92": {str(m): cp_upper(0, 92, 1 - gamma_for(m)) for m in (1, 2)},
                           "artifacts": {}}
    # primary families
    for fam, spec in FAMILIES.items():
        data = load(spec["path"])
        art = data["compiler"]["artifact"]
        gate = art["gate"]
        rows = parse_grid_rows(gate["notes"])
        report = data["compiler"]["report"]
        if fam == "issue_type":
            cands = data["compiler"]["candidates"]
            reached = sum(1 for c in cands if c.get("gate") is not None)
            m = reached
            basis = "compiler.candidates: one candidate has gate == null (retired at synthesis)"
        else:
            m = 2 if "candidates mined        2" in report or "candidates mined 2" in report.replace("  ", " ") else int(report.split("candidates mined")[1].split()[0])
            basis = "compiler.report: candidates mined 2, dominated after calibration"
        n, k = gate["n_accepted"], gate["observed_violations"]
        out["artifacts"][fam] = {
            "label": spec["label"], "artifact_id": art["artifact_id"], "m": m, "m_basis": basis,
            "n": n, "k": k, "u_per_candidate": cp_upper(k, n, 1 - gamma_for(1)),
            "u_candidate_wide": cp_upper(k, n, 1 - gamma_for(m)),
            "grid_rows": rows, "retained_u": gate["risk_upper_bound"],
            "certificate_at_alpha": "compiler-wide" if cp_upper(k, n, 1 - gamma_for(m)) <= ALPHA else "per-candidate",
            "groups_for_compiler_wide": n_min(m),
        }
    # cross-repository (frozen search, m = 1)
    for name, path in (("core", CORE), ("balanced", BALANCED), ("gate_frontier", FRONTIER)):
        data = load(path)
        for repo, block in data["repositories"].items():
            comp = block.get("compiler") or (block.get("compilers") or {}).get("learned_gate")
            if not comp or not comp.get("artifact"):
                out["artifacts"][f"{name}:{repo}"] = {"status": block.get("status", "retired"), "m": 1}
                continue
            gate = comp["artifact"]["gate"]
            out["artifacts"][f"{name}:{repo}"] = {
                "m": 1, "m_basis": "freeze_one_candidate_before_calibration = true; one candidate mined",
                "frozen": comp["config"].get("freeze_one_candidate_before_calibration"),
                "n": gate["n_accepted"], "k": gate["observed_violations"], "retained_u": gate["risk_upper_bound"],
                "u_candidate_wide": cp_upper(gate["observed_violations"], gate["n_accepted"], 1 - gamma_for(1)),
                "grid_rows": parse_grid_rows(gate["notes"]),
            }
    lines = [r"\begin{tabularx}{\linewidth}{@{}lccc>{\raggedright\arraybackslash}Xc@{}}", r"\toprule",
             r"Family & $m$ & $n_\eta/k_\eta$ & $U_{\delta/|\Lambda|}$ / $U_{\delta/(m|\Lambda|)}$ & Certificate at $\alpha=0.05$ & Groups needed \\",
             r"\midrule"]
    for fam, spec in FAMILIES.items():
        a = out["artifacts"][fam]
        cert = "compiler-wide" if a["certificate_at_alpha"] == "compiler-wide" else r"per-candidate; compiler-wide at $\alpha\ge0.057$"
        lines.append(f"{spec['label']} & {a['m']} & {a['n']}/{a['k']} & {a['u_per_candidate']:.4f} / {a['u_candidate_wide']:.4f} & {cert} & {a['groups_for_compiler_wide']} \\\\")
    lines += [r"\addlinespace[2pt]", r"Cross-repository (7 admitted) & 1 & 92/0 & 0.0498 / 0.0498 & compiler-wide (frozen search) & 92 \\", r"\bottomrule", r"\end{tabularx}"]
    write_table("multiplicity_accounting", "multiplicity", "\n".join(lines))
    dump("multiplicity_accounting", out)
    return out


