def cmd_absolute() -> dict[str, Any]:
    out: dict[str, Any] = {"families": {}, "pooled": {}}
    pooled: dict[str, dict[str, list[float]]] = {a: {m: [] for m in METRICS} for a in ("baseline", "compiled", "manual")}
    for fam, spec in FAMILIES.items():
        out["families"][fam] = {"label": spec["label"], "arms": {}}
        for arm in ("baseline", "compiled", "manual"):
            rows = rows_for(fam, arm)
            block: dict[str, Any] = {"n": len(rows), "exact": sum(exact(fam, r) for r in rows), "condition": spec["arms"][arm]}
            for m in METRICS:
                vals = [float(r["metrics"][m]) for r in rows]
                pooled[arm][m].extend(vals)
                mu, med = mean_median(vals)
                block[m] = {"mean": mu, "median": med, "sum": float(sum(vals))}
            out["families"][fam]["arms"][arm] = block
    for arm in pooled:
        out["pooled"][arm] = {m: {"mean": mean_median(v)[0], "median": mean_median(v)[1], "sum": float(sum(v)), "n": len(v)} for m, v in pooled[arm].items()}

    lines = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
             r"Family & Arm & Requests & Interfaces & Tokens & Latency (ms) & Cost (USD$\times10^{-4}$) \\",
             r"\midrule"]
    arm_label = {"baseline": "Baseline", "compiled": "Compiled", "manual": "Manual"}
    for fam, spec in FAMILIES.items():
        for i, arm in enumerate(("baseline", "compiled", "manual")):
            b = out["families"][fam]["arms"][arm]
            name = spec["label"] if i == 0 else ""
            lines.append(
                f"{name} & {arm_label[arm]} & {b['requests']['mean']:.2f} & {b['tool_calls']['mean']:.2f} & "
                f"{fmt(b['total_tokens']['mean'])} / {fmt(b['total_tokens']['median'],0)} & "
                f"{fmt(b['wall_latency_ms']['mean'],0)} / {fmt(b['wall_latency_ms']['median'],0)} & "
                f"{sci(b['estimated_cost_usd']['mean'])} / {sci(b['estimated_cost_usd']['median'])} \\\\"
            )
        lines.append(r"\addlinespace[2pt]")
    lines.append(r"\midrule")
    for i, arm in enumerate(("baseline", "compiled", "manual")):
        b = out["pooled"][arm]
        name = r"All ($n=90$)" if i == 0 else ""
        lines.append(
            f"{name} & {arm_label[arm]} & {b['requests']['mean']:.2f} & {b['tool_calls']['mean']:.2f} & "
            f"{fmt(b['total_tokens']['mean'])} / {fmt(b['total_tokens']['median'],0)} & "
            f"{fmt(b['wall_latency_ms']['mean'],0)} / {fmt(b['wall_latency_ms']['median'],0)} & "
            f"{sci(b['estimated_cost_usd']['mean'])} / {sci(b['estimated_cost_usd']['median'])} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("absolute_resources", "absolute", "\n".join(lines))
    dump("absolute_resources", out)
    return out


# --------------------------------------------------------------------------- T2.2 paired
def cmd_paired() -> dict[str, Any]:
    out: dict[str, Any] = {"families": {}, "discordance": {}}
    pooled_cells = Counter()
    for fam, spec in FAMILIES.items():
        base = {int(r[spec["id"]]): r for r in rows_for(fam, "baseline")}
        fam_out: dict[str, Any] = {}
        for arm in ("compiled", "manual"):
            cand = {int(r[spec["id"]]): r for r in rows_for(fam, arm)}
            common = sorted(set(base) & set(cand))
            contrast: dict[str, Any] = {"n_pairs": len(common)}
            for m in ("total_tokens", "wall_latency_ms", "estimated_cost_usd", "requests"):
                diffs = [float(cand[k]["metrics"][m]) - float(base[k]["metrics"][m]) for k in common]
                entry: dict[str, Any] = {
                    "mean_difference": float(statistics.mean(diffs)),
                    "mean_ci95": list(bootstrap_ci_mean_legacy(diffs)),
                    "wilcoxon_p": wilcoxon_p(diffs),
                    "aggregate_reduction": 1.0 - sum(float(cand[k]["metrics"][m]) for k in common) / sum(float(base[k]["metrics"][m]) for k in common),
                }
                if m == "wall_latency_ms":
                    entry["median_difference"] = float(statistics.median(diffs))
                    entry["median_ci95"] = list(bootstrap_ci(diffs, np.median, seed=BOOTSTRAP_SEED + 1))
                if m == "requests":
                    entry["difference_histogram"] = dict(Counter(int(d) for d in diffs))
                contrast[m] = entry
            fam_out[arm] = contrast
        # discordance (compiled vs baseline)
        cand = {int(r[spec["id"]]): r for r in rows_for(fam, "compiled")}
        common = sorted(set(base) & set(cand))
        b_only = sum(exact(fam, base[k]) and not exact(fam, cand[k]) for k in common)
        c_only = sum(exact(fam, cand[k]) and not exact(fam, base[k]) for k in common)
        both = sum(exact(fam, cand[k]) and exact(fam, base[k]) for k in common)
        neither = len(common) - b_only - c_only - both
        disc = b_only + c_only
        out["discordance"][fam] = {
            "n": len(common), "baseline_only": b_only, "compiled_only": c_only, "both": both, "neither": neither,
            "mcnemar_exact_p": float(binomtest(min(b_only, c_only), disc, 0.5).pvalue) if disc else 1.0,
            "compiled_only_failure_upper95": one_sided_upper_95(b_only, len(common)),
            "baseline_only_records": [k for k in common if exact(fam, base[k]) and not exact(fam, cand[k])],
            "compiled_only_records": [k for k in common if exact(fam, cand[k]) and not exact(fam, base[k])],
        }
        for key in ("n", "baseline_only", "compiled_only", "both", "neither"):
            pooled_cells[key] += out["discordance"][fam][key]
        out["families"][fam] = fam_out
    disc = pooled_cells["baseline_only"] + pooled_cells["compiled_only"]
    out["discordance"]["pooled"] = dict(pooled_cells) | {
        "mcnemar_exact_p": float(binomtest(min(pooled_cells["baseline_only"], pooled_cells["compiled_only"]), disc, 0.5).pvalue) if disc else 1.0,
        "compiled_only_failure_upper95": one_sided_upper_95(pooled_cells["baseline_only"], pooled_cells["n"]),
    }

    # paired table: compiled minus baseline
    def cell_ms(e: dict[str, Any], key: str, ci: str) -> str:
        return f"${e[key]:,.0f}$\\,ms $[{e[ci][0]:,.0f},\\,{e[ci][1]:,.0f}]$"

    lines = [r"\begin{tabular}{@{}llrr@{}}", r"\toprule", r"Family & Endpoint & Paired difference (95\% CI) & $p$ \\", r"\midrule"]
    for fam, spec in FAMILIES.items():
        c = out["families"][fam]["compiled"]
        tok, lat, cost = c["total_tokens"], c["wall_latency_ms"], c["estimated_cost_usd"]
        lines.append(rf"\multirow{{4}}{{*}}{{{spec['label'].split()[0]}}}")
        lines.append(_fix_sci(f" & Total tokens & ${tok['mean_difference']:,.1f}\\ [{tok['mean_ci95'][0]:,.1f},\\,{tok['mean_ci95'][1]:,.1f}]$ & ${tok['wilcoxon_p']:.1e}$ \\\\"))
        lines.append(_fix_sci(f" & Wall latency (mean) & {cell_ms(lat, 'mean_difference', 'mean_ci95')} & ${lat['wilcoxon_p']:.1e}$ \\\\"))
        lines.append(f" & Wall latency (median) & {cell_ms(lat, 'median_difference', 'median_ci95')} & --- \\\\")
        lines.append(_fix_sci(f" & Estimated cost & $-\\${abs(cost['mean_difference'])*1e4:.2f}\\times10^{{-4}}\\ [-{abs(cost['mean_ci95'][0])*1e4:.2f},\\,-{abs(cost['mean_ci95'][1])*1e4:.2f}]\\times10^{{-4}}$ & ${cost['wilcoxon_p']:.1e}$ \\\\"))
        lines.append(r"\addlinespace[1pt]")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("paired_statistics", "paired", "\n".join(lines))

    d = out["discordance"]
    lines = [r"\begin{tabular}{@{}lrrrrrr@{}}", r"\toprule",
             r"Family & $n$ & Both pass & Baseline-only & Compiled-only & McNemar $p$ & Upper bound \\", r"\midrule"]
    for fam, spec in FAMILIES.items():
        x = d[fam]
        lines.append(f"{spec['label'].split()[0]} & {x['n']} & {x['both']} & {x['baseline_only']} & {x['compiled_only']} & {x['mcnemar_exact_p']:.2f} & {100*x['compiled_only_failure_upper95']:.1f}\\% \\\\")
    x = d["pooled"]
    lines += [r"\midrule", f"Pooled & {x['n']} & {x['both']} & {x['baseline_only']} & {x['compiled_only']} & {x['mcnemar_exact_p']:.2f} & {100*x['compiled_only_failure_upper95']:.1f}\\% \\\\",
              r"\bottomrule", r"\end{tabular}"]
    write_table("discordance", "paired", "\n".join(lines))
    dump("paired_statistics", out)
    return out


def _fix_sci(line: str) -> str:
    """Render Python ``1.7e-06`` inside $...$ as ``1.7\times10^{-6}``."""
    import re
    return re.sub(r"(\d\.\d)e-0?(\d+)", lambda m: rf"{m.group(1)}\times10^{{-{int(m.group(2))}}}", line)


