"""Recompute the fresh-issue single-look feasibility record and regenerate its table; no provider call.

Rebuilds the preflight from the retained time-forward snapshot and the retained result trees,
requires it to equal the retained ``preflight.json`` byte for byte (as parsed JSON), checks that
no provider-side artifact exists for a study that was declared no-go, recomputes the exact
admission floors independently of the preflight's helper, and writes ``audit_tf.json``, the
generated table ``paper/iclr/tables/gate_single_look.tex`` and the appendix snippet
``paper/iclr/notes/snippets/gate_single_look_paragraph.tex``.

If a run is ever added (a protocol amendment), this audit must be extended to recompute its
counts, bounds and decision from retained records before the table may report them.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
for path in (ROOT, ROOT / "src", ROOT / "paper/scripts"):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

import graded_issue_gate_tf_preflight as preflight  # noqa: E402
from guarded_agentic_compaction.grc.calibrate import GRID, clopper_pearson_upper  # noqa: E402

AUDIT_PATH = preflight.STUDY_DIR / "audit_tf.json"
TABLE_PATH = ROOT / "paper/iclr/tables/gate_single_look.tex"
SNIPPET_PATH = ROOT / "paper/iclr/notes/snippets/gate_single_look_paragraph.tex"
PROVIDER_ARTIFACTS = ("checkpoint.json", "results_tf.json", "candidate_tf", "episodes", "spend_ledger.json")


def independent_max_k(n: int) -> int:
    """Largest k admitted at level 0.1/11 and alpha 0.05, by bisection on the exact bound."""
    conf = 1.0 - preflight.DELTA / len(GRID)
    if n <= 0 or clopper_pearson_upper(0, n, conf) > preflight.ALPHA:
        return -1
    lo, hi = 0, n
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if clopper_pearson_upper(mid, n, conf) <= preflight.ALPHA:
            lo = mid
        else:
            hi = mid - 1
    return lo


def audit() -> dict:
    retained = json.loads(preflight.OUT.read_text())
    rebuilt = preflight.build()
    if rebuilt != retained:
        raise ValueError("retained preflight.json differs from a provider-free rebuild")
    present = [name for name in PROVIDER_ARTIFACTS if (preflight.STUDY_DIR / name).exists()]
    if retained["status"] != "go" and present:
        raise ValueError(f"no-go study has provider-side artifacts: {present}")
    floors_ok = all(independent_max_k(int(n)) == k for n, k in retained["admission_floors_registered_grid_m1"].items())
    for design in retained["design"].values():
        n_acc = design["accepted_at_eta_0.50_if_all_dispatch"]
        if independent_max_k(n_acc) != design["max_admissible_k_at_eta_0.50"]:
            raise ValueError("max admissible k disagrees with the independent bisection")
        for rate, prob in design["admission_probability_at_assumed_error_rate"].items():
            kmax = design["max_admissible_k_at_eta_0.50"]
            expect = sum(math.comb(n_acc, j) * float(rate) ** j * (1 - float(rate)) ** (n_acc - j)
                         for j in range(kmax + 1)) if kmax >= 0 else 0.0
            if abs(expect - prob) > 1e-4:
                raise ValueError("admission probability disagrees with the independent binomial sum")
    pool = retained["pool_accounting"]
    if pool["issues_without_comments"] + pool["issues_with_at_least_one_comment"] != pool["issues_in_snapshot"]:
        raise ValueError("pool accounting does not add up")
    return {"schema": "gac-graded-issue-gate-tf-audit/v1", "provider_calls_executed": 0,
            "preflight_matches_rebuild": True, "floors_match_independent_bisection": floors_ok,
            "provider_side_artifacts_present": present, "status": retained["status"],
            "calibration_groups": {k: v["calibration_groups"] for k, v in retained["design"].items()},
            "minimum_calibration_groups": preflight.MIN_CALIBRATION_GROUPS,
            "preflight_sha256": preflight.sha256(preflight.OUT)}


def table(retained: dict) -> str:
    pool = retained["pool_accounting"]
    dist = retained["descriptor_distribution"]["all_issues_with_comments"]
    lit, gen = (retained["design"][k] for k in ("literal_exclusion", "same_record_space_exclusion"))
    p_lit = lit["admission_probability_at_assumed_error_rate"]["0.0153"]
    p_gen = gen["admission_probability_at_assumed_error_rate"]["0.0153"]

    def k_text(design: dict) -> str:
        k = design["max_admissible_k_at_eta_0.50"]
        return "none" if k < 0 else str(k)

    def feat(name: str) -> str:
        return f"{dist[name]['mean']:.2f}"

    lines = [
        "% generated by paper/scripts/audit_graded_issue_gate_tf.py table; do not edit",
        r"\begin{tabular}{@{}lrr@{}}",
        r"\toprule",
        r"Quantity & Literal rule & Same-space rule \\",
        r"\midrule",
        rf"Issues in post-cutoff snapshot & \multicolumn{{2}}{{r}}{{{pool['issues_in_snapshot']}}} \\",
        rf"\quad with at least one comment & \multicolumn{{2}}{{r}}{{{pool['issues_with_at_least_one_comment']}}} \\",
        rf"\quad Markdown link / bare URL / plain text & \multicolumn{{2}}{{r}}{{{dist['markdown_link']} / {dist['bare_url']} / {dist['plain_text']}}} \\",
        rf"\quad means: $\log(1{{+}}\text{{comments}})$ / labels / title length$^{{\dagger}}$ / age (y) & \multicolumn{{2}}{{r}}{{{feat('log_comments')} / {feat('label_count')} / {feat('title_length')} / {feat('age_years')}}} \\",
        rf"Pool after exclusion & {pool['pool_literal_rule']} & {pool['pool_same_record_space_rule']} \\",
        rf"Calibration groups after {preflight.DISCOVERY_ISSUES} discovery & {lit['calibration_groups']} & {gen['calibration_groups']} \\",
        rf"Registered minimum (about) & \multicolumn{{2}}{{r}}{{{preflight.MIN_CALIBRATION_GROUPS}}} \\",
        rf"Accepted at $\eta=0.50$ if all dispatch & {lit['accepted_at_eta_0.50_if_all_dispatch']} & {gen['accepted_at_eta_0.50_if_all_dispatch']} \\",
        rf"Largest admissible $k$ at $\eta=0.50$ & {k_text(lit)} & {k_text(gen)} \\",
        rf"Admission probability at 1.5\% error rate & {p_lit:.2f} & {p_gen:.2f} \\",
        r"\midrule",
        r"\multicolumn{3}{@{}l}{Decision: no-go; the replication was not run and no provider call was made.} \\",
        r"\multicolumn{3}{@{}p{0.95\linewidth}}{\footnotesize Literal rule: every \texttt{issue\_number} or \texttt{record\_number} under \texttt{paper/results} and \texttt{experiments}. Same-space rule: only numbers that could name a \texttt{huggingface/datasets} record (other record spaces such as BIRD question ids and other repositories' pull requests removed). $^{\dagger}$Characters/100.} \\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def snippet(retained: dict) -> str:
    pool = retained["pool_accounting"]
    lit, gen = (retained["design"][k] for k in ("literal_exclusion", "same_record_space_exclusion"))
    dist = retained["descriptor_distribution"]["all_issues_with_comments"]
    return (
        "% generated by paper/scripts/audit_graded_issue_gate_tf.py table; do not edit\n"
        "\\paragraph{Fresh-issue single-look replication of the learned gate (not run).}\n"
        f"We designed a single-look prospective replication of the frozen graded-gate score on independent "
        f"post-cutoff \\texttt{{huggingface/datasets}} issues and checked its feasibility without a provider call. "
        f"The snapshot holds {pool['issues_in_snapshot']} issues, {pool['issues_with_at_least_one_comment']} with at least "
        f"one comment ({dist['markdown_link']} with a Markdown link, {dist['bare_url']} with a bare URL in the first three comments). "
        f"Excluding every record number that any retained study mentions leaves {pool['pool_literal_rule']} issues; "
        f"the most generous reading, which removes only numbers that could name a record of this repository, leaves "
        f"{pool['pool_same_record_space_rule']}. After {preflight.DISCOVERY_ISSUES} issues for re-deriving the candidate, "
        f"{lit['calibration_groups']} and {gen['calibration_groups']} calibration groups remain, against the about "
        f"{preflight.MIN_CALIBRATION_GROUPS} the design needs: at the registered level "
        f"{'no' if gen['max_admissible_k_at_eta_0.50'] <= 0 else 'at most ' + str(gen['max_admissible_k_at_eta_0.50'])} errors could be tolerated among roughly {gen['accepted_at_eta_0.50_if_all_dispatch']} "
        f"accepted groups, so admission would be unlikely even if the sequential extension's 1.5\\% error rate held. "
        f"We therefore did not run it, and the sequential extension remains the only evidence on this workload: "
        f"exploratory, adaptive, and not a certificate.\n")


def main() -> None:
    result = audit()
    retained = json.loads(preflight.OUT.read_text())
    AUDIT_PATH.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    TABLE_PATH.write_text(table(retained))
    SNIPPET_PATH.parent.mkdir(parents=True, exist_ok=True)
    SNIPPET_PATH.write_text(snippet(retained))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
